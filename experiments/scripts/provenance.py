"""Provenance manifest: which code produced which result artefact, identified by content hash and commit.

    python scripts/provenance.py   -> PROVENANCE.md

For every artefact: sha256 of its content, the producing script, and depends_on_commit = the last commit that
touched the producing code at or before the commit in which the artefact's results were first recorded. The
evidence of order is the repository's commit chronology plus content hashes, not file-system timestamps.
Also verifies that (i) the producing code is unchanged between depends_on_commit and HEAD, and (ii) derived
reports can be regenerated byte-for-byte from the recorded results with the frozen code.
Checkpoints are not in git; they are listed by name, size and sha256 with the result JSON each one produced.
"""
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

ERA5_CODE = ["scripts/era5_confirm.py", "scripts/m0_one.py", "scripts/o1.py", "scripts/e5_dev.py",
             "scripts/run_phase.py", "scrl"]
# (artefact, producer command, producing code, file whose first commit records the results, role)
ARTEFACTS = [
    ("results/era5_train.txt", "era5_confirm.py --train (stdout)", ERA5_CODE, "results/era5_confirm.json",
     "ERA5 training log (24 runs)"),
    ("results/era5_eval.txt", "era5_confirm.py --evaluate (stdout)", ERA5_CODE, "results/era5_confirm.json",
     "ERA5 evaluation log"),
    ("results/era5_confirm.json", "era5_confirm.py --evaluate", ERA5_CODE, "results/era5_confirm.json",
     "ERA5 per-seed results (all methods)"),
    ("results/era5_report.txt", "era5_confirm.py --report", ERA5_CODE, "results/era5_confirm.json",
     "ERA5 preregistered comparisons"),
    ("results/e5_dev.json", "e5_dev.py", ["scripts/e5_dev.py", "scrl"], "results/e5_dev.json",
     "E5 development self-check (discovery data only)"),
    ("results/o1_train.txt", "o1.py (training stdout)", ["scripts/o1.py", "scripts/m0_one.py", "scrl"],
     "results/o1.json", "Gate O1 training log"),
    ("results/o1.json", "o1.py", ["scripts/o1.py", "scripts/m0_one.py", "scrl"], "results/o1.json",
     "Gate O1 per-seed results"),
    ("results/grid_m0.txt", "run_m0.py (stdout)", ["scripts/run_m0.py", "scripts/m0_one.py", "scrl"],
     "results/m0/bucket/model1__s0.json", "Gate M0 training log"),
    ("results/conv_train.txt", "conv_check.py (training stdout)", ["scripts/conv_check.py", "scripts/m0_one.py",
                                                                    "scrl"],
     "results/conv_check.json", "HPD convergence check training log"),
    ("results/grid_ladder.txt", "run_ladder.py (stdout)", ["scripts/run_ladder.py", "scripts/run_synthetic.py",
                                                          "scrl"],
     "results/ladder_B0/gaussian__tn_hetero__raw__s0.json", "Bucket ablation ladder training log"),
    ("figures/paper/figure_data.json", "make_figures.py", ["scripts/make_figures.py"],
     "last:figures/paper/figure_data.json", "all numbers drawn in the paper figures"),
]
REGENERATE = [("results/era5_report.txt", ["scripts/era5_confirm.py", "--report"])]


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    head = git("rev-parse", "--short", "HEAD")
    lines = ["# PROVENANCE (generated by `scripts/provenance.py`; do not edit by hand)", "",
             f"Generated at commit `{head}`. Order of events is established by commit chronology and content "
             "hashes; file-system timestamps are not used as evidence.", "",
             "## ERA5 held-out confirmation: fixed order of commits", ""]
    for c, what in (("1ecb339", "E5 specification freeze"), ("bfa2185", "ERA5 preregistration"),
                    ("50d1fb9", "E5 implementation + feasibility revision (development self-check)"),
                    ("b53a50d", "ERA5 runner freeze (loader and runner committed before any ERA5 model run)"),
                    ("69103db", "ERA5 results")):
        subj = git("log", "-1", "--format=%s", c)
        lines.append(f"- `{c}` {what} -- \"{subj}\"")
    order = git("rev-list", "--reverse", "1ecb339^..69103db").split()
    idx = [next(i for i, h in enumerate(order) if h.startswith(c))
           for c in ("1ecb339", "bfa2185", "50d1fb9", "b53a50d", "69103db")]
    assert idx == sorted(idx), "commit chain out of order"
    changed = git("diff", "--name-only", "b53a50d", "69103db", "--", *ERA5_CODE)
    assert not changed, f"ERA5 code changed between runner freeze and results: {changed}"
    lines += ["", "Checks: the five commits are ancestors in this order on the first-parent history; the ERA5 "
              "producing code (`" + "`, `".join(ERA5_CODE) + "`) has no change between `b53a50d` and `69103db`.",
              "", "## Artefacts", "",
              "| artifact | sha256 | produced_by | depends_on_commit | results_commit | code unchanged to HEAD | role |",
              "|---|---|---|---|---|---|---|"]
    later = {}
    for art, cmd, code, anchor, role in ARTEFACTS:
        if anchor.startswith("last:"):          # regenerated artefact: the commit that last recorded it
            res_commit = git("log", "-1", "--format=%h", "--", anchor[5:])
        else:                                   # run result: the commit that first recorded it
            res_commit = git("log", "--diff-filter=A", "--format=%h", "--", anchor).split()[-1]
        dep = git("log", "-1", "--format=%h", res_commit, "--", *code)
        same = not git("diff", "--name-only", dep, "HEAD", "--", *code)
        note = " (same commit as results)" if dep == res_commit else ""
        lines.append(f"| `{art}` | `{sha(ROOT / art)}` | `{cmd}` | `{dep}`{note} | `{res_commit}` | "
                     f"{'yes' if same else 'no, see below'} | {role} |")
        if not same:
            later[art] = [f"{f.split('experiments/')[-1]} (+{ad}/-{de})" for ad, de, f in
                          (x.split("	") for x in git("diff", "--numstat", dep, "HEAD", "--", *code).splitlines())]
    lines += ["", "Code changed after an artefact's results were recorded (these results were not rerun; the diff "
              "shows what later work added):", ""]
    for art, stat in later.items():
        lines.append(f"- `{art}`: " + "; ".join(stat))
    lines += ["", "## Regeneration checks", ""]
    for art, cmd in REGENERATE:
        out = subprocess.run([sys.executable, *cmd], cwd=ROOT, capture_output=True, check=True).stdout
        ok = hashlib.sha256(out).hexdigest() == sha(ROOT / art)
        assert ok, f"{art} does not regenerate byte-for-byte"
        lines.append(f"- `{art}` regenerated by `{' '.join(Path(c).name for c in cmd)}` from the recorded results "
                     f"with the code at `{head}`: byte-identical (sha256 match).")
    lines += ["", "## ERA5 checkpoints (not in git)", "",
              "| checkpoint | model | seed | bytes | sha256 | result JSON | result sha256 |", "|---|---|---|---|---|---|---|"]
    for m in (1, 2, 3):
        for s in range(8):
            ck = ROOT / "checkpoints" / "m0_rerun" / "era5_cloud" / f"model{m}__s{s}.pt"
            rj = ROOT / "results" / "m0_rerun" / "era5_cloud" / f"model{m}__s{s}.json"
            lines.append(f"| `{ck.relative_to(ROOT).as_posix()}` | {m} | {s} | {ck.stat().st_size} | `{sha(ck)}` | "
                         f"`{rj.relative_to(ROOT).as_posix()}` | `{sha(rj)}` |")
    (ROOT / "PROVENANCE.md").write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"wrote PROVENANCE.md ({len(ARTEFACTS)} artefacts, 24 checkpoints)")


if __name__ == "__main__":
    main()
